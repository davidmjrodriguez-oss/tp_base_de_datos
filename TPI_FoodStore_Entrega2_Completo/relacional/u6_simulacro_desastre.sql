-- --------------------------------------------------------------------------
-- Paso 2: Generar respaldo de referencia desde la base sana
--         (se ejecuta desde el sistema operativo, no desde psql)
-- --------------------------------------------------------------------------
\echo
\echo '=== PASO 2: Generar respaldo de referencia (ejecutar en SO) ==='
\echo 'pg_dump -h localhost -U postgres -d :db_origen -F c -b -v -f :archivo_backup'
