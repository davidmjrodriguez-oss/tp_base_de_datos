DROP DATABASE IF EXISTS :db_destino;
CREATE DATABASE :db_destino;

\echo 'Base :db_destino creada vacía (simula servidor nuevo después del desastre)'

-- --------------------------------------------------------------------------
-- Paso 4: Restaurar desde el respaldo MIDIENDO EL TIEMPO
-- --------------------------------------------------------------------------
\echo
\echo '=== PASO 4: Restauración desde el respaldo ==='
\echo 'pg_restore -h localhost -U postgres -d :db_destino -v :archivo_backup'
\echo '(Comando a ejecutar en terminal: pg_restore -h localhost -U postgres -d food_store_restaurada -v C:\respaldos\food_store_simulacro.backup)'
\echo
\echo 'NOTA: Medir el tiempo con: time pg_restore ... o medir antes/después en el SO.'

-- --------------------------------------------------------------------------
-- Paso 5: Verificar integridad de los datos restaurados
-- --------------------------------------------------------------------------
\echo
\echo '=== PASO 5: Verificación de integridad tras restauración ==='
\c :db_destino

-- 5a. Conteo de filas por tabla
SELECT 'categoria'  AS tabla, count(*) AS filas FROM categoria
UNION ALL SELECT 'producto', count(*) FROM producto
UNION ALL SELECT 'etiqueta', count(*) FROM etiqueta
UNION ALL SELECT 'producto_etiqueta', count(*) FROM producto_etiqueta
UNION ALL SELECT 'pedido', count(*) FROM pedido
UNION ALL SELECT 'detalle_pedido', count(*) FROM detalle_pedido;

-- 5b. Huella de productos (debe coincidir con la base sana)
\echo '=== Huella de la base DESPUÉS de la restauración ==='
SELECT md5(string_agg(id || ':' || nombre, ',' ORDER BY id)) AS huella_productos_despues
FROM producto;

-- 5c. Verificación de integridad referencial (FK huérfanas)
SELECT 'detalle_pedido sin pedido' AS problema, COUNT(*) AS cantidad
FROM detalle_pedido dp LEFT JOIN pedido p ON p.id = dp.pedido_id WHERE p.id IS NULL
UNION ALL
SELECT 'detalle_pedido sin producto', COUNT(*)
FROM detalle_pedido dp LEFT JOIN producto pr ON pr.id = dp.producto_id WHERE pr.id IS NULL
UNION ALL
SELECT 'producto_etiqueta sin producto', COUNT(*)
FROM producto_etiqueta pe LEFT JOIN producto pr ON pr.id = pe.producto_id WHERE pr.id IS NULL
UNION ALL
SELECT 'producto_etiqueta sin etiqueta', COUNT(*)
FROM producto_etiqueta pe LEFT JOIN etiqueta e ON e.id = pe.etiqueta_id WHERE e.id IS NULL;

-- 5d. Prueba de lectura y escritura en la base restaurada
