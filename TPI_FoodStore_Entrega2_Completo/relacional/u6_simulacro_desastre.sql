-- Crear tablas del esquema Food Store en la base de origen
\c :db_origen

DROP TABLE IF EXISTS detalle_pedido CASCADE;
DROP TABLE IF EXISTS pedido CASCADE;
DROP TABLE IF EXISTS producto_etiqueta CASCADE;
DROP TABLE IF EXISTS producto CASCADE;
DROP TABLE IF EXISTS etiqueta CASCADE;
DROP TABLE IF EXISTS categoria CASCADE;

CREATE TABLE categoria (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre    VARCHAR(80) NOT NULL UNIQUE,
    descripcion VARCHAR(200),
    activo    BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE producto (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(120) NOT NULL,
    descripcion  VARCHAR(200),
    precio       NUMERIC(12,2) NOT NULL CHECK (precio > 0),
    stock        INTEGER NOT NULL DEFAULT 0 CHECK (stock >= 0),
    imagen_url   VARCHAR(255),
    categoria_id BIGINT NOT NULL REFERENCES categoria(id),
    activo       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE etiqueta (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE producto_etiqueta (
    producto_id BIGINT NOT NULL REFERENCES producto(id),
    etiqueta_id BIGINT NOT NULL REFERENCES etiqueta(id),
    PRIMARY KEY (producto_id, etiqueta_id)
);

CREATE TABLE pedido (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_nombre VARCHAR(80) NOT NULL,
    direccion_entrega VARCHAR(200) NOT NULL,
    forma_pago     VARCHAR(20) NOT NULL CHECK (forma_pago IN ('EFECTIVO','TRANSFERENCIA')),
    notas          VARCHAR(200),
    estado         VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE' CHECK (estado IN ('PENDIENTE','EN_PREPARACION','ENTREGADO','CANCELADO')),
    total          NUMERIC(12,2) NOT NULL DEFAULT 0,
    fecha          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE detalle_pedido (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id   BIGINT NOT NULL REFERENCES pedido(id),
    producto_id BIGINT NOT NULL REFERENCES producto(id),
    nombre_producto VARCHAR(60) NOT NULL,
    precio_unitario NUMERIC(12,2) NOT NULL,
    cantidad    INTEGER NOT NULL CHECK (cantidad > 0),
    subtotal    NUMERIC(12,2) NOT NULL
);

