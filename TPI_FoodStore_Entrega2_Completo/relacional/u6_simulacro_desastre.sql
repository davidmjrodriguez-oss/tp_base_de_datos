-- Huella de la base sana (para verificar después de la restauración)
\echo '=== Huella de la base ANTES del desastre ==='
SELECT (SELECT count(*) FROM categoria)  AS categorias,
       (SELECT count(*) FROM producto)   AS productos,
       (SELECT count(*) FROM etiqueta)   AS etiquetas,
       (SELECT count(*) FROM producto_etiqueta) AS producto_etiqueta,
       (SELECT count(*) FROM pedido)     AS pedidos,
       (SELECT count(*) FROM detalle_pedido) AS detalles,
       md5(string_agg(id || ':' || nombre, ',' ORDER BY id)) AS huella_productos
