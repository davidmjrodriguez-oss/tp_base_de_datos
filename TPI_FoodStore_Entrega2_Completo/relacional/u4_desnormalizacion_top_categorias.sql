-- ---------------------------------------------------------------------
-- 3. (5.2 c) Estructura desnormalizada + mecanismo de sincronización
--
-- ventas_categoria_dia(fecha, categoria) guarda el monto vendido ya sumado.
-- Fuente de verdad: detalle_pedido + pedido + producto (+ categoria para el nombre).
-- Un detalle aporta su subtotal a (fecha del pedido, categoría del producto)
-- si y solo si detalle.eliminado = FALSE y pedido.eliminado = FALSE.
--
-- Mecanismo: triggers AFTER ROW que, ante cualquier cambio que altere un
-- aporte, restan el aporte viejo y suman el nuevo (deltas) con un UPSERT
-- atómico. Todo ocurre en la misma transacción que el cambio de origen.
-- ---------------------------------------------------------------------

-- Índices de soporte que los triggers necesitan para localizar detalles
-- (se crean DESPUÉS de medir el "antes", para no alterarlo).
CREATE INDEX idx_detalle_pedido_pedido   ON detalle_pedido (pedido_id);
CREATE INDEX idx_detalle_pedido_producto ON detalle_pedido (producto_id);

BEGIN;
-- Bloqueo breve para que no se cuele ninguna escritura entre la carga inicial
-- y la activación de los triggers.
LOCK TABLE detalle_pedido, pedido, producto, categoria IN SHARE ROW EXCLUSIVE MODE;

CREATE TABLE ventas_categoria_dia (
    fecha            DATE          NOT NULL,
    categoria_id     BIGINT        NOT NULL REFERENCES categoria(id),
    categoria_nombre VARCHAR(80)   NOT NULL,                 -- dato redundante (copia de categoria.nombre)
    total_vendido    NUMERIC(16,2) NOT NULL DEFAULT 0,       -- dato redundante (agregado)
    PRIMARY KEY (fecha, categoria_id)
);

-- Soporta WHERE fecha = ? ORDER BY total_vendido DESC LIMIT 5
CREATE INDEX idx_vcd_fecha_total ON ventas_categoria_dia (fecha, total_vendido DESC);

-- Carga inicial (migración): se calcula una vez desde la fuente de verdad.
INSERT INTO ventas_categoria_dia (fecha, categoria_id, categoria_nombre, total_vendido)
SELECT ped.fecha, c.id, c.nombre, SUM(dp.subtotal)
FROM detalle_pedido dp
JOIN pedido ped  ON ped.id = dp.pedido_id
JOIN producto pr ON pr.id  = dp.producto_id
JOIN categoria c ON c.id   = pr.categoria_id
WHERE dp.eliminado = FALSE AND ped.eliminado = FALSE
GROUP BY ped.fecha, c.id, c.nombre;

-- Suma (o resta, con delta negativo) un monto a la fila (fecha, categoría).
CREATE FUNCTION fn_vcd_aplicar(p_fecha DATE, p_categoria BIGINT, p_delta NUMERIC) RETURNS VOID AS $$
BEGIN
    IF p_delta = 0 THEN
        RETURN;
    END IF;
    INSERT INTO ventas_categoria_dia (fecha, categoria_id, categoria_nombre, total_vendido)
    SELECT p_fecha, c.id, c.nombre, p_delta
    FROM categoria c
    WHERE c.id = p_categoria
    ON CONFLICT (fecha, categoria_id)
    DO UPDATE SET total_vendido = ventas_categoria_dia.total_vendido + EXCLUDED.total_vendido;
END $$ LANGUAGE plpgsql;

-- (1) Cambios en detalle_pedido: INSERT, DELETE y UPDATE de subtotal / eliminado /
--     pedido_id / producto_id. Resta el aporte OLD y suma el aporte NEW.
CREATE FUNCTION fn_vcd_detalle() RETURNS trigger AS $$
DECLARE
    v_fecha DATE;
    v_elim  BOOLEAN;
    v_cat   BIGINT;
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE') AND NOT OLD.eliminado THEN
        SELECT ped.fecha, ped.eliminado INTO v_fecha, v_elim FROM pedido ped WHERE ped.id = OLD.pedido_id;
        IF FOUND AND NOT v_elim THEN
            SELECT categoria_id INTO v_cat FROM producto WHERE id = OLD.producto_id;
            PERFORM fn_vcd_aplicar(v_fecha, v_cat, -OLD.subtotal);
        END IF;
    END IF;
    IF TG_OP IN ('INSERT', 'UPDATE') AND NOT NEW.eliminado THEN
        SELECT ped.fecha, ped.eliminado INTO v_fecha, v_elim FROM pedido ped WHERE ped.id = NEW.pedido_id;
        IF FOUND AND NOT v_elim THEN
            SELECT categoria_id INTO v_cat FROM producto WHERE id = NEW.producto_id;
            PERFORM fn_vcd_aplicar(v_fecha, v_cat, NEW.subtotal);
        END IF;
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_vcd_detalle_ins_del
AFTER INSERT OR DELETE ON detalle_pedido
FOR EACH ROW EXECUTE FUNCTION fn_vcd_detalle();

CREATE TRIGGER trg_vcd_detalle_upd
AFTER UPDATE OF pedido_id, producto_id, subtotal, eliminado ON detalle_pedido
FOR EACH ROW EXECUTE FUNCTION fn_vcd_detalle();

-- (2) Cambios en pedido: baja lógica o cambio de fecha mueven todos sus detalles.
CREATE FUNCTION fn_vcd_pedido() RETURNS trigger AS $$
DECLARE
    r RECORD;
BEGIN
    IF NOT OLD.eliminado THEN
        FOR r IN SELECT pr.categoria_id AS cat, SUM(dp.subtotal) AS monto
                 FROM detalle_pedido dp JOIN producto pr ON pr.id = dp.producto_id
                 WHERE dp.pedido_id = NEW.id AND NOT dp.eliminado
                 GROUP BY pr.categoria_id
        LOOP
            PERFORM fn_vcd_aplicar(OLD.fecha, r.cat, -r.monto);
        END LOOP;
    END IF;
    IF NOT NEW.eliminado THEN
        FOR r IN SELECT pr.categoria_id AS cat, SUM(dp.subtotal) AS monto
                 FROM detalle_pedido dp JOIN producto pr ON pr.id = dp.producto_id
                 WHERE dp.pedido_id = NEW.id AND NOT dp.eliminado
                 GROUP BY pr.categoria_id
        LOOP
            PERFORM fn_vcd_aplicar(NEW.fecha, r.cat, r.monto);
        END LOOP;
    END IF;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_vcd_pedido
AFTER UPDATE OF fecha, eliminado ON pedido
FOR EACH ROW
WHEN (OLD.fecha IS DISTINCT FROM NEW.fecha OR OLD.eliminado IS DISTINCT FROM NEW.eliminado)
EXECUTE FUNCTION fn_vcd_pedido();

-- (3) Reclasificación de un producto: sus ventas pasan de una categoría a otra.
CREATE FUNCTION fn_vcd_producto() RETURNS trigger AS $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN SELECT ped.fecha, SUM(dp.subtotal) AS monto
             FROM detalle_pedido dp JOIN pedido ped ON ped.id = dp.pedido_id
             WHERE dp.producto_id = NEW.id AND NOT dp.eliminado AND NOT ped.eliminado
             GROUP BY ped.fecha
    LOOP
        PERFORM fn_vcd_aplicar(r.fecha, OLD.categoria_id, -r.monto);
        PERFORM fn_vcd_aplicar(r.fecha, NEW.categoria_id,  r.monto);
    END LOOP;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_vcd_producto
AFTER UPDATE OF categoria_id ON producto
FOR EACH ROW
WHEN (OLD.categoria_id IS DISTINCT FROM NEW.categoria_id)
EXECUTE FUNCTION fn_vcd_producto();

-- (4) Renombre de una categoría: se propaga la copia redundante del nombre.
CREATE FUNCTION fn_vcd_categoria() RETURNS trigger AS $$
BEGIN
    UPDATE ventas_categoria_dia SET categoria_nombre = NEW.nombre WHERE categoria_id = NEW.id;
    RETURN NULL;
END $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_vcd_categoria
AFTER UPDATE OF nombre ON categoria
FOR EACH ROW
WHEN (OLD.nombre IS DISTINCT FROM NEW.nombre)
EXECUTE FUNCTION fn_vcd_categoria();

