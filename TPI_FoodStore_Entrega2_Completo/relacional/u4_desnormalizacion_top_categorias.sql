-- ---------------------------------------------------------------------
-- 5. (5.2 e) Auditoría: ¿el dato redundante se desincronizó de su fuente?
--    Devuelve una fila por cada discrepancia (resultado vacío = todo en orden).
-- ---------------------------------------------------------------------
CREATE VIEW v_auditoria_ventas_categoria_dia AS
-- Discrepancias de monto (incluye filas faltantes, sobrantes o con total distinto)
SELECT COALESCE(v.fecha, f.fecha)               AS fecha,
       COALESCE(v.categoria_id, f.categoria_id) AS categoria_id,
       'TOTAL'::text                            AS tipo,
       v.total_vendido                          AS valor_resumen,
       f.total_vendido                          AS valor_fuente
FROM ventas_categoria_dia v
FULL JOIN (
    SELECT ped.fecha, pr.categoria_id, SUM(dp.subtotal) AS total_vendido
    FROM detalle_pedido dp
    JOIN pedido ped  ON ped.id = dp.pedido_id
    JOIN producto pr ON pr.id  = dp.producto_id
    WHERE dp.eliminado = FALSE AND ped.eliminado = FALSE
    GROUP BY ped.fecha, pr.categoria_id
) f ON f.fecha = v.fecha AND f.categoria_id = v.categoria_id
WHERE COALESCE(v.total_vendido, 0) <> COALESCE(f.total_vendido, 0)
UNION ALL
-- Discrepancias en la copia redundante del nombre de la categoría
SELECT v.fecha, v.categoria_id, 'NOMBRE'::text, NULL::numeric, NULL::numeric
FROM ventas_categoria_dia v
JOIN categoria c ON c.id = v.categoria_id
WHERE v.categoria_nombre <> c.nombre;

